type TranslationKey = keyof typeof translations.en;
type JaKeys = keyof typeof translations.ja;

interface LangContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey) => string;
}

const LangContext = createContext<LangContextType>({
  lang: "en",
  setLang: () => {},
  t: (key: TranslationKey) => key,
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = localStorage.getItem("vibecode-hunt-lang");
    if (stored === "zh" || stored === "en" || stored === "ja") {
      setLangState(stored);
    }
  }, []);

  const setLang = useCallback((newLang: Lang) => {
    setLangState(newLang);
    localStorage.setItem("vibecode-hunt-lang", newLang);
  }, []);

  const t = useCallback(
    (key: TranslationKey): string => {
      if (lang === "ja") {
        const jaVal = translations.ja[key as JaKeys];
        if (jaVal !== undefined) return jaVal;
        return translations.en[key] ?? key;
      }
      return translations[lang][key] ?? key;
    },
    [lang]
  );

  return React.createElement(LangContext.Provider, { value: { lang, setLang, t } }, children);
}

export function useLang() {
  return useContext(LangContext);
}
